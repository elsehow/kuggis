#!/usr/bin/env bash
# VM setup for box, run by `box sync` (and so by `box new`). Re-runnable:
# every step either checks first or rewrites what box owns.
set -euo pipefail
. ~/.box/config
REPO=$HOME/${BOX_REPO##*/}
chmod +x ~/.box/*.sh ~/.box/needs-you ~/.box/git-hooks/*

need=''
for c in tmux jq git curl; do command -v $c >/dev/null || need="$need $c"; done
if [ -n "$need" ]; then
  sudo apt-get update -qq
  # shellcheck disable=SC2086
  sudo DEBIAN_FRONTEND=noninteractive apt-get install -y -qq $need
fi

# Claude signs in with the setup-token only: no API key, no gateway, and so
# no claude.ai connectors either.
cat >~/.box/env <<'EOF'
# Generated by box's bootstrap.sh; sourced by the session scripts and ~/.bashrc.
export CLAUDE_CODE_OAUTH_TOKEN="$(cat ~/.box/token)"
unset ANTHROPIC_API_KEY ANTHROPIC_AUTH_TOKEN ANTHROPIC_BASE_URL
export GH_HOST=github.int.exe.xyz
export PATH="$HOME/.local/bin:$HOME/.bun/bin:$HOME/.cargo/bin:$PATH"
# Secrets: KEY=value lines; blank values are skipped rather than exported empty.
if [ -f ~/.box/secrets.env ]; then
  set -a; . <(grep -E '^[A-Za-z_][A-Za-z0-9_]*=.+' ~/.box/secrets.env); set +a
fi
EOF
grep -qF '.box/env' ~/.bashrc 2>/dev/null || echo '[ -f ~/.box/env ] && . ~/.box/env' >>~/.bashrc
. ~/.box/env

git config --global user.name "$BOX_GIT_NAME"
git config --global user.email "$BOX_GIT_EMAIL"
git config --global push.autoSetupRemote true
git config --global core.hooksPath ~/.box/git-hooks # the Box: commit trailer

if [ ! -d "$REPO/.git" ]; then
  echo "cloning ${BOX_REPO}…"
  git clone -q "https://github.int.exe.xyz/$BOX_REPO.git" "$REPO"
fi
grep -qxF '.claude/worktrees/' "$REPO/.git/info/exclude" 2>/dev/null ||
  echo '.claude/worktrees/' >>"$REPO/.git/info/exclude"
mkdir -p "$REPO/.claude/worktrees" ~/.box/state ~/.box/needs ~/inbox ~/.claude

# User settings: box owns these keys and the five hook events. The theme
# follows the laptop terminal's light/dark mode.
s=~/.claude/settings.json
[ -s "$s" ] || echo '{}' >"$s"
jq --arg h "$HOME/.box/hook.sh" --arg mode "$BOX_MODE" --argjson prefs "${BOX_CLAUDE_PREFS:-{\}}" '
  def hook(arg): [{hooks: [{type: "command", command: ($h + " " + arg)}]}];
  del(.apiKeyHelper, .env.ANTHROPIC_BASE_URL, .env.ANTHROPIC_API_KEY)
  | . + $prefs
  | .disableClaudeAiConnectors = true
  | .theme = "auto"
  | .permissions.defaultMode = $mode
  | .permissions.allow = ((.permissions.allow // []) - ["Bash(~/.box/needs-you:*)"] + ["Bash(~/.box/needs-you:*)"])
  | .hooks.UserPromptSubmit = hook("prompt")
  | .hooks.PreToolUse = [{matcher: "AskUserQuestion", hooks: hook("waiting")[0].hooks}]
  | .hooks.PostToolUse = hook("working")
  | .hooks.Stop = hook("idle")
  | .hooks.Notification = [{matcher: "permission_prompt|elicitation_dialog", hooks: hook("waiting")[0].hooks}]
' "$s" >"$s.tmp" && mv "$s.tmp" "$s"

# Trust is keyed on the main checkout, so this covers every worktree.
# Onboarding is marked done because its login picker ignores the token and
# would start a full claude.ai sign-in, connectors and all.
c=~/.claude.json
[ -s "$c" ] || echo '{}' >"$c"
jq --arg r "$REPO" '
  .projects[$r].hasTrustDialogAccepted = true
  | .hasCompletedOnboarding = true
  | del(.theme)
' "$c" >"$c.tmp" && mv "$c.tmp" "$c"

# Both agents get box's instructions as a marked block appended to their
# user-level file, below whatever the image put there.
mkdir -p ~/.codex
block=$(
  sed -e "s#{{REPO}}#$REPO#g" -e "s#{{REPO_SLUG}}#$BOX_REPO#g" -e '/^<!-- \/box -->$/d' ~/.box/CLAUDE.md
  if [ -f ~/.box/profile.md ]; then echo; cat ~/.box/profile.md; fi
  echo '<!-- /box -->'
)
for f in ~/.claude/CLAUDE.md ~/.codex/AGENTS.md; do
  touch "$f"
  sed -i '/^<!-- box -->$/,/^<!-- \/box -->$/d' "$f"
  if [ -s "$f" ] && [ -n "$(tail -n1 "$f")" ]; then echo >>"$f"; fi
  printf '%s\n' "$block" >>"$f"
done
if [ ! -f ~/.tmux.conf ] || head -1 ~/.tmux.conf | grep -q "^# box"; then
  { cat ~/.box/tmux.conf; printf "set -g @box_project '%s'\n" "$BOX_PROJECT"; } >~/.tmux.conf
  tmux source-file ~/.tmux.conf 2>/dev/null || true # a running server picks it up now
fi

# Codex talks to exe.dev's `codex` LLM integration (your ChatGPT sign-in,
# held by exe.dev), so no OpenAI credential lands here. box owns this file;
# a pre-existing one is set aside once, and trust entries survive re-syncs.
cx=~/.codex/config.toml
if [ -f "$cx" ] && ! head -1 "$cx" | grep -q '^# box'; then mv "$cx" "$cx.before-box"; fi
trusted=$(sed -n 's/^\[projects\."\(.*\)"\]$/\1/p' "$cx" 2>/dev/null || true)
{
  echo '# box: written by bootstrap.sh; [projects] entries are kept on re-sync'
  echo 'model_provider = "box"'
  printf 'notify = ["%s", "ping"]\n\n' "$HOME/.box/hook.sh"
  echo '[model_providers.box]'
  echo 'name = "exe.dev codex integration"'
  echo 'base_url = "https://codex.int.exe.xyz/v1"'
  echo 'requires_openai_auth = false'
  # shellcheck disable=SC2086
  printf '%s\n' "$REPO" $trusted | sort -u | while read -r p; do
    printf '\n[projects."%s"]\ntrust_level = "trusted"\n' "$p"
  done
} >"$cx.tmp" && mv "$cx.tmp" "$cx"

if [ -f ~/.box/profile.sh ]; then
  . ~/.box/profile.sh
  if type box_setup >/dev/null 2>&1; then
    echo "running the project profile…"
    (cd "$REPO" && box_setup)
  fi
fi

echo "claude $(claude --version 2>/dev/null || echo 'not found'); repo at $REPO"
